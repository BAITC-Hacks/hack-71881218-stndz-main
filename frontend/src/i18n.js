export function t(locale, key, ...args) {
  const dict = LOCALES[locale] || LOCALES.ru
  const val = key.split('.').reduce((o, k) => (o == null ? o : o[k]), dict)
  if (typeof val === 'function') return val(...args)
  return val ?? key
}
